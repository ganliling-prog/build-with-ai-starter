import { MarketAsset, CandlePoint } from '../types/market';

// Helper to generate realistic candle bars based on a base price and trend
export function generateCandles(
  basePrice: number,
  count: number,
  volatilityPct: number = 0.015,
  driftPct: number = 0.002
): CandlePoint[] {
  const candles: CandlePoint[] = [];
  let currentClose = basePrice * (1 - (driftPct * count) / 2);
  const now = Date.now();
  const stepMs = 60 * 1000 * 15; // 15-min intervals for 1D, or scaled

  for (let i = 0; i < count; i++) {
    const time = new Date(now - (count - i) * stepMs).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const change = currentClose * (volatilityPct * (Math.random() - 0.48) + driftPct);
    const open = currentClose;
    const close = Math.max(0.01, open + change);
    const high = Math.max(open, close) + Math.random() * (open * volatilityPct * 0.5);
    const low = Math.min(open, close) - Math.random() * (open * volatilityPct * 0.5);
    const volume = Math.floor(10000 + Math.random() * 90000);

    candles.push({
      timestamp: time,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });

    currentClose = close;
  }
  return candles;
}

export function generateSparkline(candles: CandlePoint[]): number[] {
  return candles.map((c) => c.close);
}

